import { test, expect } from "@playwright/test";
import { existsSync, readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";

test("acceptance with local Alice and Wizard of Oz", async ({ page }) => {
  test.setTimeout(90000);
  const files = ["Alice's Adventures in Wonderland by Lewis Carroll.epub", "The Wonderful Wizard of Oz by L. Frank Baum.epub"].map(name => path.resolve(name));
  test.skip(files.some(file => !existsSync(file)), "Requires both optional local EPUBs");
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  const keys = files.map(file => "epub-position:" + createHash("sha256").update(readFileSync(file)).digest("hex"));
  const position = (i: number) => page.evaluate(key => localStorage.getItem(key), keys[i]);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/");
  await expect(page.getByRole("button", { name: "导入 EPUB", exact: true })).toBeEnabled();
  await page.getByLabel("选择 EPUB 文件").setInputFiles(files);
  const oz = page.getByRole("tab", { name: "The Wonderful Wizard of Oz", exact: true });
  const alice = page.getByRole("tab", { name: /Alice/ });
  await expect(oz).toHaveAttribute("aria-selected", "true");
  const chapter = page.getByRole("button", { name: "Chapter II The Council with the Munchkins", exact: true });
  await expect(chapter).toBeEnabled(); await chapter.click();
  await expect(chapter).toHaveAttribute("aria-current", "location");
  await expect(page.locator(".page-controls")).toContainText(/\d+%/);
  const initial = await position(1);
  const bounds = (await page.locator(".epub-host").boundingBox())!;
  await page.mouse.move(bounds.x + 120, bounds.y + 120); await page.mouse.wheel(0, 120);
  await expect.poll(() => position(1)).not.toBe(initial);
  const ozPosition = await position(1);
  await alice.click();
  const aliceChapter = page.getByRole("button", { name: "CHAPTER II. The Pool of Tears", exact: true });
  await expect(aliceChapter).toBeEnabled(); await aliceChapter.click();
  await page.getByRole("button", { name: "下一页", exact: true }).click();
  await expect(page.getByRole("button", { name: "上一页", exact: true })).toBeEnabled();
  await expect.poll(() => position(0)).toMatch(/^epubcfi/);
  const alicePosition = await position(0);
  await oz.click(); await expect(chapter).toHaveAttribute("aria-current", "location");
  await expect.poll(() => position(1)).toBe(ozPosition);
  await page.getByRole("button", { name: "排版", exact: true }).click();
  await page.getByLabel("视图", { exact: true }).selectOption("single");
  await page.getByLabel("字体", { exact: true }).selectOption("sans");
  await page.getByLabel("正文字号").selectOption("24");
  await page.getByLabel("行高", { exact: true }).selectOption("2");
  await expect.poll(() => page.frameLocator("iframe").first().locator("p").first().evaluate(el => getComputedStyle(el).fontSize)).toBe("24px");
  await expect.poll(() => position(1)).toBe(ozPosition);
  await page.getByLabel("视图", { exact: true }).selectOption("double");
  await page.getByRole("button", { name: "背景", exact: true }).click();
  await page.getByRole("button", { name: "背景 米黄", exact: true }).click();
  await page.getByRole("button", { name: "主题色 松绿", exact: true }).click();
  await page.getByLabel("界面模式", { exact: true }).selectOption("light");
  await expect.poll(() => page.frameLocator("iframe").first().locator("body").evaluate(el => getComputedStyle(el).backgroundColor)).toBe("rgb(243, 232, 207)");
  await page.reload();
  await expect(oz).toHaveAttribute("aria-selected", "true");
  await expect.poll(() => position(1)).toBe(ozPosition);
  await expect(page.locator("html")).toHaveAttribute("data-theme", "light");
  await alice.click(); await expect(aliceChapter).toHaveAttribute("aria-current", "location");
  await expect.poll(() => position(0)).toBe(alicePosition);
  await expect(page.locator("iframe").first()).not.toHaveAttribute("sandbox", /allow-scripts/);
  expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight)).toBe(true);
  await expect(page.locator(".page-controls")).toContainText(/\d+%/);
  await page.screenshot({ path: "test-results/acceptance-reader.png" });
  await page.getByRole("button", { name: "关闭阅读，返回书架" }).click();
  await expect(page.locator(".book-card")).toHaveCount(2);
  await expect(page.locator(".book-card img")).toHaveCount(2);
  for (const img of await page.locator(".book-card img").all()) expect(await img.evaluate(el => (el as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
  await page.screenshot({ path: "test-results/acceptance-shelf.png" });
  await page.reload(); await expect(page.locator(".book-card")).toHaveCount(2);
  expect(errors).toEqual([]);
});
